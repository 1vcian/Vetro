//! Estensioni crittografiche: vettori noti (FIPS-197), verificati anche
//! contro QEMU.

use vetro_isa_tests::case;

/// Byte di uno stato AES (ordine di memoria) come valore del registro.
fn st(b: [u8; 16]) -> u128 {
    u128::from_le_bytes(b)
}

#[test]
fn aes128_first_round_fips197() {
    // FIPS-197 C.1: plaintext 00112233..., chiave 00010203...
    let pt =
        st([0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff]);
    let key =
        st([0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f]);
    let s_row =
        st([0x63, 0x53, 0xe0, 0x8c, 0x09, 0x60, 0xe1, 0x04, 0xcd, 0x70, 0xb7, 0x51, 0xba, 0xca, 0xd0, 0xe7]);
    let m_col =
        st([0x5f, 0x72, 0x64, 0x15, 0x57, 0xf5, 0xbc, 0x92, 0xf7, 0xbe, 0x3b, 0x29, 0x1d, 0xb9, 0xf9, 0x1a]);
    case(
        "aes128_first_round_fips197",
        &[
            0x4e284820, // aese v0.16b, v1.16b
            0x4e286802, // aesmc v2.16b, v0.16b
        ],
    )
    .v(0, pt)
    .v(1, key)
    .want_v(0, s_row)
    .want_v(2, m_col)
    .run();
}
